defmodule FinalTrack.NeiamAuthAdapter do
  @moduledoc """
  Hands neiam_auth (OIDC) logins to the app's own accounts code.
  Generated by `mix neiam_auth.install --flavour gen_auth_18`, then shaped
  after clayman's.

  `PROVISION=auto` creates a passwordless, confirmed account whose display
  name comes from the provider's `name` claim. An existing account is only
  ever matched by email (`get_user_by_email/1`).

  No role flags: groups are recorded on the identity row only.

  Who must sign in through SSO is neiam_auth's own rule (`sso_required?/1`):
  under `OIDC_LOGIN_MODE=sso`, accounts linked to a provider with
  `REQUIRED_FOR_LINKED=true`. The sign-in paths ask
  `NeiamAuth.password_login_allowed?/1`.

  Under `OIDC_LOGIN_MODE=sso_strict` an addressed invite is accepted by
  signing in with NEIAM: `FinalTrackWeb.InviteController.sso/2` remembers the
  invite, the login is refused as not invited (and kept pending), and
  `handle_error/2` sends the browser back to the invite to finish.
  `InviteController.register/2` then creates the passwordless account and
  links the pending login to it.
  """

  @behaviour NeiamAuth.Adapter

  require Logger

  alias FinalTrack.Accounts
  alias FinalTrack.Accounts.User
  alias FinalTrack.Repo

  @impl true
  def get_user_by_email(email), do: Accounts.get_user_by_email(email)

  @impl true
  def log_in(conn, user) do
    FinalTrackWeb.UserAuth.log_in_user(conn, user, %{"remember_me" => "true"})
  end

  @impl true
  def current_user(conn) do
    case conn.assigns[:current_scope] do
      %{user: user} -> user
      _ -> nil
    end
  end

  # PROVISION=auto (or PROVISION_GROUPS) only. A passwordless, confirmed user
  # whose display name comes from the IdP.
  @impl true
  def register_sso_user(%NeiamAuth.Claims{email: email} = claims) when is_binary(email) do
    %User{}
    |> User.registration_changeset(%{email: email})
    |> Ecto.Changeset.put_change(:display_name, claims.name)
    |> Ecto.Changeset.put_change(:confirmed_at, DateTime.utc_now(:second))
    |> Repo.insert()
    |> tap(fn
      {:error, %Ecto.Changeset{errors: errors}} ->
        Logger.warning(
          "neiam_auth: auto-provisioning #{claims.provider} sub=#{claims.sub} refused: " <>
            inspect(Keyword.keys(errors))
        )

      _ ->
        :ok
    end)
  end

  def register_sso_user(_claims), do: {:error, :no_email}

  # No guest kind: every account can be linked.
  @impl true
  def linkable?(%User{}), do: true

  # No role flags; the groups are still recorded on the identity.
  @impl true
  def apply_groups(user, _groups), do: {:ok, user}

  @impl true
  def sso_required?(user), do: NeiamAuth.sso_required?(user)

  @impl true
  def handle_error(conn, :not_invited) do
    case Plug.Conn.get_session(conn, :final_track_invite) do
      token when is_binary(token) ->
        conn
        |> Plug.Conn.put_session(:final_track_invite_sso, token)
        |> Phoenix.Controller.put_flash(
          :info,
          "Signed in with NEIAM. Confirm below to finish accepting your invite."
        )
        |> Phoenix.Controller.redirect(to: "/users/register?" <> URI.encode_query(invite: token))

      _ ->
        default_error(conn, :not_invited)
    end
  end

  def handle_error(conn, reason), do: default_error(conn, reason)

  # neiam_auth's own behaviour without the callback.
  defp default_error(conn, reason) do
    conn
    |> Phoenix.Controller.put_flash(:error, NeiamAuth.Controller.message(reason))
    |> Phoenix.Controller.redirect(to: login_path())
  end

  @impl true
  def login_path, do: "/users/log-in"

  @impl true
  def settings_path, do: "/users/settings"
end
